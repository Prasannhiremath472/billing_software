CREATE TABLE payments (
  id VARCHAR(40) NOT NULL,
  invoice_id VARCHAR(40) NOT NULL,
  invoice_number VARCHAR(40) NOT NULL,
  customer_id VARCHAR(40) NULL,
  customer_name VARCHAR(160) NOT NULL,
  method VARCHAR(20) NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  reference_number VARCHAR(80) NULL,
  payment_date DATETIME(3) NOT NULL,
  cashier_id VARCHAR(40) NOT NULL,
  cashier_name VARCHAR(120) NOT NULL,
  notes VARCHAR(500) NULL,
  PRIMARY KEY (id),
  KEY idx_payments_invoice (invoice_id),
  KEY idx_payments_date (payment_date),
  KEY idx_payments_method (method),
  CONSTRAINT fk_payments_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE,
  CONSTRAINT fk_payments_cashier FOREIGN KEY (cashier_id) REFERENCES users (id),
  CONSTRAINT chk_payments_amount CHECK (amount >= 0)
) ENGINE=InnoDB;

CREATE TABLE credit_notes (
  id VARCHAR(40) NOT NULL,
  credit_note_number VARCHAR(40) NOT NULL,
  original_invoice_id VARCHAR(40) NOT NULL,
  original_invoice_number VARCHAR(40) NOT NULL,
  customer_id VARCHAR(40) NULL,
