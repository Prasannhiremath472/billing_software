  customer_city VARCHAR(80) NULL,
  customer_state VARCHAR(80) NULL,
  customer_state_code VARCHAR(4) NULL,
  customer_gstin VARCHAR(20) NULL,
  customer_pan VARCHAR(12) NULL,
