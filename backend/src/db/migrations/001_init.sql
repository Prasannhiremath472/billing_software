-- JewelSync POS: initial schema (MySQL 8, InnoDB, utf8mb4)

CREATE TABLE users (
  id VARCHAR(40) NOT NULL,
  name VARCHAR(120) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'Cashier',
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(20) NULL,
  password_hash VARCHAR(100) NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  last_login_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_email (email),
  CONSTRAINT chk_users_role CHECK (role IN ('Admin','Manager','Cashier'))
) ENGINE=InnoDB;

CREATE TABLE store_info (
  id VARCHAR(40) NOT NULL,
  name VARCHAR(160) NOT NULL,
  trade_name VARCHAR(160) NULL,
  legal_name VARCHAR(200) NULL,
  address VARCHAR(300) NOT NULL DEFAULT '',
  city VARCHAR(80) NOT NULL DEFAULT '',
  state VARCHAR(80) NOT NULL DEFAULT '',
  state_code VARCHAR(4) NULL,
  pincode VARCHAR(10) NOT NULL DEFAULT '',
  phone VARCHAR(30) NOT NULL DEFAULT '',
  email VARCHAR(190) NOT NULL DEFAULT '',
  gstin VARCHAR(20) NOT NULL DEFAULT '',
  pan VARCHAR(12) NULL,
  logo_url VARCHAR(500) NULL,
  return_policy TEXT NOT NULL,
  thank_you_message TEXT NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE app_settings (
  setting_key VARCHAR(60) NOT NULL,
  setting_value JSON NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (setting_key)
) ENGINE=InnoDB;

CREATE TABLE document_sequences (
  seq_key VARCHAR(60) NOT NULL,
  current_value INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (seq_key)
) ENGINE=InnoDB;

CREATE TABLE metal_rates (
  id VARCHAR(40) NOT NULL,
  metal_type VARCHAR(30) NOT NULL,
  purity VARCHAR(30) NOT NULL,
  rate_per_gram DECIMAL(12,2) NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by VARCHAR(40) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_metal_rates_metal_purity (metal_type, purity),
  CONSTRAINT fk_metal_rates_user FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE metal_rate_history (
  id VARCHAR(40) NOT NULL,
  metal_type VARCHAR(30) NOT NULL,
  purity VARCHAR(30) NOT NULL,
  rate_per_gram DECIMAL(12,2) NOT NULL,
  rate_date DATE NOT NULL,
  updated_by VARCHAR(40) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_rate_history_metal_date (metal_type, purity, rate_date),
  CONSTRAINT fk_rate_history_user FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB;

